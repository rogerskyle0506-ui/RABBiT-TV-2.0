// Helper function to quickly lookup a channel's category
export function getChannelCategory(channelName: string): string {
  for (const [category, channels] of Object.entries(channelCategories)) {
    if (channels.includes(channelName)) {
      return category;
    }
  }
  return "Entertainment & Drama"; // Default fallback category
}

// Helper to get all channels belonging to a specific category tab
export function getChannelsByCategoryName(categoryName: string, allChannels: any[]): any[] {
  if (categoryName === "All") return allChannels;
  
  const targetChannelNames = channelCategories[categoryName] || [];
  return allChannels.filter((c) => targetChannelNames.includes(c.title || c.name));
}
